public static class FiscalOperationRuleMappingExtensions
{
    public static FiscalOperationRuleDto ToDto(this FiscalOperationRule r) =>
        new(
            r.Id,
            r.Description,
            (int)r.Finalidade,
            r.Finalidade.ToDescription(),
            r.CfopStateInternal,
            r.CfopInterstate,
            r.CstCsosnIcms,
            r.ModBcIcms,
            r.AliqIcms,
            r.ReducaoBcIcms,
            r.ModBcIcmsSt,
            r.MvaIcmsSt,
            r.ReducaoBcIcmsSt,
            r.AliqIcmsSt,
            r.MotivoDesoneracaoIcms,
            r.AliqCreditoSimples,
            r.CstIpi,
            r.CodigoEnquadramentoIpi,
            r.AliqIpi,
            r.CstPis,
            r.AliqPis,
            r.CstCofins,
            r.AliqCofins,
            r.CstIbs,
            r.AliqIbs,
            r.CstCbs,
            r.AliqCbs,
            r.ClassificacaoTributaria,
            r.AdditionalNotes,
            r.IsActive,
            r.Exceptions.Select(e => new FiscalRuleExceptionDto(
                e.Id,
                e.SpecificDestinationState,
                e.SpecificNcmStart,
                e.SpecificOrigin,
                e.CfopStateInternal,
                e.CfopInterstate,
                e.CstCsosnIcms,
                e.ModBcIcms,
                e.AliqIcms,
                e.ReducaoBcIcms,
                e.ModBcIcmsSt,
                e.MvaIcmsSt,
                e.ReducaoBcIcmsSt,
                e.AliqIcmsSt,
                e.MotivoDesoneracaoIcms,
                e.AliqCreditoSimples,
                e.CstIpi,
                e.CodigoEnquadramentoIpi,
                e.AliqIpi,
                e.CstPis,
                e.AliqPis,
                e.CstCofins,
                e.AliqCofins,
                e.CstIbs,
                e.AliqIbs,
                e.CstCbs,
                e.AliqCbs,
                e.ClassificacaoTributaria,
                e.AdditionalNotes,
                e.IsActive
            )).ToList()
        );

    public static string ToDescription(this FiscalDocumentType finalidade) =>
        finalidade switch
        {
            FiscalDocumentType.Normal => "1 - NF-e Normal",
            FiscalDocumentType.Complementar => "2 - NF-e Complementar",
            FiscalDocumentType.Ajuste => "3 - NF-e de Ajuste",
            FiscalDocumentType.Devolucao => "4 - Devolução / Retorno",
            FiscalDocumentType.NotaCredito => "5 - Nota de Crédito (RT)",
            FiscalDocumentType.NotaDebito => "6 - Nota de Débito (RT)",
            _ => "1 - NF-e Normal"
        };
}